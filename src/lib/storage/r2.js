import { S3Client, DeleteObjectCommand, PutObjectCommand } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

// ─────────────────────────────────────────────────────────────────────────────
// Cloudflare R2 storage driver.
//
// The browser uploads DIRECTLY to R2 using a presigned PUT URL that this module
// signs — the file never passes through a route handler, which is what keeps
// 500 MB videos clear of the ~4.5 MB serverless request-body limit and works on
// a read-only filesystem.
//
// Bucket prerequisites (both are dashboard settings, not code):
//   1. Public read — either a custom domain on the bucket or the r2.dev public
//      development URL. Whichever it is goes in NEXT_PUBLIC_R2_PUBLIC_BASE_URL.
//   2. A CORS policy allowing PUT from this site's origin, otherwise the
//      browser refuses the presigned upload before it ever leaves the tab:
//        [{ "AllowedOrigins": ["http://localhost:3000", "https://<prod>"],
//           "AllowedMethods": ["GET", "PUT", "HEAD"],
//           "AllowedHeaders": ["content-type"],
//           "ExposeHeaders": ["etag"] }]
// ─────────────────────────────────────────────────────────────────────────────

// How long a presigned upload URL stays valid. Long enough for a slow phone to
// push a large video over a bad connection, short enough that a URL leaked from
// a browser history is not a standing write grant.
const UPLOAD_URL_TTL_SECONDS = 60 * 60; // 1 hour

function required(name) {
  const value = process.env[name];
  if (!value) {
    throw new Error(`${name} is not set — required when STORAGE_DRIVER=r2.`);
  }
  return value;
}

// Trailing slashes would produce "//" in every public URL. Harmless for R2 but
// ugly in the database and it breaks `keyFromUrl`'s prefix match.
function publicBase() {
  return required("NEXT_PUBLIC_R2_PUBLIC_BASE_URL").replace(/\/+$/, "");
}

let client;

function s3() {
  if (!client) {
    client = new S3Client({
      // R2 is single-region behind the scenes; "auto" is what Cloudflare's own
      // docs specify, and the SDK still requires *something* here.
      region: "auto",
      endpoint: `https://${required("R2_ACCOUNT_ID")}.r2.cloudflarestorage.com`,
      credentials: {
        accessKeyId: required("R2_ACCESS_KEY_ID"),
        secretAccessKey: required("R2_SECRET_ACCESS_KEY"),
      },
    });
  }
  return client;
}

export function publicUrl(key) {
  // Keys are generated by us from a sanitized filename, so the only characters
  // needing escaping are the ones a sanitized name can still contain.
  return `${publicBase()}/${key.split("/").map(encodeURIComponent).join("/")}`;
}

// The inverse of publicUrl. Returns null for anything this bucket does not
// serve — external URLs pasted by an admin and legacy /uploads/ paths both land
// here, and the caller treats null as "not ours, leave it alone".
export function keyFromUrl(url) {
  if (typeof url !== "string") return null;

  const prefix = `${publicBase()}/`;
  if (!url.startsWith(prefix)) return null;

  try {
    return decodeURIComponent(url.slice(prefix.length));
  } catch {
    return null;
  }
}

// Signs a one-shot PUT for exactly this key and content type.
//
// `signableHeaders` is load-bearing. By default the presigner signs only `host`,
// which leaves Content-Type as a free parameter the client picks — so a URL
// issued for a JPEG could be used to store text/html, and the bucket is publicly
// readable. Naming it here puts content-type in X-Amz-SignedHeaders, so R2
// rejects (403) any PUT whose header does not match what the server approved.
// The Content-Type also decides whether a browser renders the object inline or
// downloads it, so it is worth pinning for correctness alone.
export async function createUploadTarget(key, contentType) {
  const url = await getSignedUrl(
    s3(),
    new PutObjectCommand({
      Bucket: required("R2_BUCKET"),
      Key: key,
      ContentType: contentType,
    }),
    {
      expiresIn: UPLOAD_URL_TTL_SECONDS,
      signableHeaders: new Set(["content-type"]),
    }
  );

  return {
    method: "PUT",
    url,
    // Must match the signed ContentType byte for byte or R2 answers 403.
    headers: { "content-type": contentType },
  };
}

export async function remove(key) {
  await s3().send(
    new DeleteObjectCommand({ Bucket: required("R2_BUCKET"), Key: key })
  );
}
